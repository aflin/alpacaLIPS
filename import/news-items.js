#!/usr/bin/env rampart
/* Parse the cached current-events portal pages into one row per news
 * item, in the news database beside the article pages.
 *
 *   rampart news-items.js [--db DIR] [--src DIR] [--dry-run]
 *
 * WHY ROWS. The portal months are already searchable as four documents,
 * but a month-sized document is a poor retrieval unit: a model asking
 * "what happened on 4 November" or "the last week of politics" needs the
 * item, its date, its section and its sources. This produces that.
 *
 * WHY FROM THE CACHE. The cached HTML carries the source URLs and the
 * nesting; the extracted text has lost both. The cache is append-only,
 * so this can be re-run at any time and is deterministic -- which is why
 * the table is simply rebuilt rather than merged into.
 *
 * THE MARKUP is machine-generated by the portal templates and regular:
 *   div.current-events-main           one per day
 *     span.bday                       the ISO date
 *     div.current-events-content      the day's items
 *       <p><b>Section</b></p>         e.g. "Armed conflicts and attacks"
 *       <ul><li>context<ul><li>item   nesting is the context breadcrumb
 *         a.external                  the item's sources
 * A leaf <li> -- one with no nested list -- is an item. Its ancestors
 * are its breadcrumb.
 */
rampart.globalize(rampart.utils);
var Sql  = require("rampart-sql");
var html = require("rampart-html");

/* The tree this file sits in, so a clone anywhere works. */
var LIPS = process.env.LIPS || rampart.utils.realPath(process.scriptPath + "/..");
var DB  = LIPS + "/build/news";
var SRC = LIPS + "/build/news-src";
var DRY = 0;
for (var i = 2; i < process.argv.length; i++) {
    var a = process.argv[i];
    if      (a === "--db")      DB  = process.argv[++i];
    else if (a === "--src")     SRC = process.argv[++i];
    else if (a === "--dry-run") DRY = 1;
    else { printf("unknown option %s\n", a); process.exit(1); }
}
var PORTALS = SRC + "/cache/portal";

/* ---------- helpers -------------------------------------------------- */
function textOf(frag) {
    /* The HTML engine does the entity decoding and tag stripping; doing
       either by hand on wiki markup is how mojibake gets in. */
    var t = html.newDocument("<div>" + frag + "</div>").toText();
    t = (t && t.length) ? String(t[0]) : "";
    t = t.replace(/\s+/g, " ");
    /* Text extraction puts a space either side of every inline link, so
       prose comes out as "Bermuda -flagged" and "country 's". Close the
       gap before punctuation and after an opening bracket; nothing else
       is touched. */
    t = t.replace(/\s+([,.;:!?%)\]}])/g, "$1")
         .replace(/([([{])\s+/g, "$1")
         .replace(/\s+('|\u2019)(s\b|t\b)/g, "$1$2")
         .replace(/\s+-\s*(flagged|based|led|owned|backed|held|born)\b/g, "-$1");
    return t.replace(/^\s+|\s+$/g, "");
}

var RE_EXT  = /href="(https?:\/\/[^"]+)"[^>]*class="external text"[^>]*>([\s\S]*?)<\/a>/g;
/* Newspaper names are italicised -- (<i>The Guardian</i>) -- so the
   label has to be read as markup, not as a flat capture. */
var RE_EXTEL = /<a[^>]*class="external text"[^>]*>[\s\S]*?<\/a>/g;
var RE_WIKI = /rel="mw:WikiLink"[^>]*href="\.\/([^"#]+)"/g;

function sourcesOf(frag) {
    var out = [], m;
    RE_EXT.lastIndex = 0;
    while ((m = RE_EXT.exec(frag)) !== null) {
        var label = textOf(m[2]).replace(/^\(|\)$/g, "").trim();
        out.push((label || "source") + "\t" + m[1]);
    }
    return out;
}
function linksOf(frag) {
    var out = {}, m;
    RE_WIKI.lastIndex = 0;
    while ((m = RE_WIKI.exec(frag)) !== null) out[decodeURIComponent(m[1])] = 1;
    return Object.keys(out);
}

/* ---------- walk one day's content ---------------------------------- */
/* A token scan rather than DOM recursion: rampart-html hands back lists
   of elements, not a tree to walk, and the nesting is what carries the
   context here. */
function itemsOfDay(content, date, emit) {
    var section = "";
    var stack = [];           /* breadcrumb label per nesting level */
    var stackLinks = [];      /* and the articles those labels link to */
    var depth = 0;
    var buf = "";             /* current <li>'s own markup */
    var re = /<p><b>([^<]+)<\/b><\/p>|<(ul|li)\b[^>]*>|<\/(ul|li)>/g;
    var pos = 0, m;
    while ((m = re.exec(content)) !== null) {
        buf += content.substring(pos, m.index);
        pos = m.index + m[0].length;
        if (m[1] !== undefined) {               /* a section heading */
            section = m[1].replace(/\s+/g, " ").trim();
            stack = []; depth = 0; buf = "";
        } else if (m[2] === "ul") {             /* this li has children */
            var label = textOf(buf);
            if (label) stack[depth] = label;
            /* The parent's links matter more than the item's own: the
               breadcrumb is "Middle Eastern crisis / 2026 Iran war /
               2026 Strait of Hormuz crisis", and THOSE are the articles
               written about the situation. Capturing only the leaf's
               links gave Oman, Panama and Oil tanker -- true, but not
               what a reader of the item wants next. */
            stackLinks[depth] = linksOf(buf);
            depth++;
            buf = "";
        } else if (m[2] === "li") {
            buf = "";
        } else if (m[3] === "ul") {
            depth--; if (depth < 0) depth = 0;
            stack.length = depth;
            stackLinks.length = depth;
            buf = "";
        } else if (m[3] === "li") {
            /* Drop the citation anchors from the prose: they are kept in
               their own column, and "(CNBC)" mid-sentence is noise to a
               reader and to a retrieval score alike. */
            var txt = textOf(buf.replace(RE_EXTEL, ""));
            /* A section is required: the day block also contains the
               "Ongoing events" sidebar, whose entries are bare topic
               names ("Strait of Hormuz crisis") sitting outside any
               <p><b>section</b></p>. 76 of 2,291 rows were those. */
            if (section && txt && txt.length > 20) {   /* a leaf item */
                /* Topic links first, innermost first: the most specific
                   situation article is the most useful next read. The
                   item's own links follow as background. */
                var ls = [], seenL = {};
                for (var d = depth - 1; d >= 0; d--)
                    (stackLinks[d] || []).forEach(function (t) {
                        if (!seenL[t]) { seenL[t] = 1; ls.push(t); }
                    });
                linksOf(buf).forEach(function (t) {
                    if (!seenL[t]) { seenL[t] = 1; ls.push(t); }
                });
                emit({ date: date, section: section,
                       topic: stack.slice(0, depth).filter(function (x) {
                           return x && x.length;
                       }).join(" / "),
                       text: txt,
                       sources: sourcesOf(buf),
                       links: ls });
            }
            buf = "";
        }
    }
}

/* ---------- walk the months ----------------------------------------- */
var files = stat(PORTALS) ? readdir(PORTALS).filter(function (f) {
    return /\.html$/.test(f);
}).sort() : [];
if (!files.length) { printf("no cached portal pages in %s\n", PORTALS); process.exit(1); }

var items = [], days = {};
files.forEach(function (f) {
    var raw = readFile(PORTALS + "/" + f, { returnString: true });
    /* Day blocks, sliced on the container the portal template emits. */
    /* Split on the class alone: the day container carries role, id and
       aria-label before it (<div role="region" ... class="current-events-main
       vevent">), so anchoring on "<div class=" matches nothing. */
    var parts = raw.split('class="current-events-main');
    var n0 = items.length;
    for (var k = 1; k < parts.length; k++) {
        var blk = parts[k];
        var d = /<span class="bday[^"]*"[^>]*>(\d{4}-\d{2}-\d{2})</.exec(blk);
        if (!d) continue;
        var c = blk.indexOf('current-events-content');
        if (c < 0) continue;
        days[d[1]] = 1;
        /* Cut the "Ongoing events" sidebar off the end of the day's
           content. Requiring a section was not enough: the sidebar is
           rendered after the last section of the final day of a month,
           so its entries inherited that heading and arrived filed under
           "Sports". It is a list of situation names, not news. */
        var content = blk.substring(c);
        var sb = content.indexOf("current-events-sidebar");
        if (sb > -1) content = content.substring(0, sb);
        itemsOfDay(content, d[1], function (it) { items.push(it); });
    }
    printf("  %-22s %4d items\n", f.replace(/\.html$/, ""), items.length - n0);
});

var dates = Object.keys(days).sort();
printf("\nparsed   : %d items over %d days (%s .. %s)\n",
       items.length, dates.length, dates[0], dates[dates.length - 1]);
var withSrc = items.filter(function (i) { return i.sources.length; }).length;
printf("with a source link: %d (%.0f%%)\n", withSrc, 100 * withSrc / items.length);

if (DRY) {
    printf("\nfirst three items:\n");
    items.slice(0, 3).forEach(function (it) {
        printf("\n  %s  [%s]\n  topic: %s\n  %s\n  sources: %s\n",
               it.date, it.section, it.topic || "(none)",
               it.text.substring(0, 160),
               it.sources.map(function (s) { return s.split("\t")[0]; }).join(" "));
    });
    process.exit(0);
}

/* ---------- write them ---------------------------------------------- */
/* Rebuilt, not merged: the parse is deterministic from an append-only
   cache, so a fresh table cannot drift from it, and 1,600 rows index in
   under a second. */
var sql = new Sql.init(DB, true);
function drop(t) { try { sql.exec("drop table " + t + ";"); } catch (e) {} }
drop("news"); drop("news_meta");

sql.exec("create table news (Id counter, Date varchar(10), Section varchar(48), " +
         "Topic varchar(160), Doc varchar(520), Sources varchar(360), " +
         "Links varchar(420));");
sql.exec("create table news_meta (Prop varchar(24), Val varchar(64));");

var ins = "insert into news (Id, Date, Section, Topic, Doc, Sources, Links) " +
          "values (counter, ?, ?, ?, ?, ?, ?);";
items.forEach(function (it) {
    sql.exec(ins, [it.date, it.section, it.topic, it.text,
                   it.sources.join("\n"), it.links.join(" ")]);
});

/* The coverage window, so a tool can state what it does and does not
   know rather than answering from whatever its newest row happens to be.
   Read from the ZIM sidecar the builder wrote. */
var meta = {};
readdir(SRC + "/out").forEach(function (f) {
    if (/\.zim\.meta\.json$/.test(f)) {
        try { meta = JSON.parse(readFile(SRC + "/out/" + f, { returnString: true })); }
        catch (e) {}
    }
});
[["windowStart", meta.windowStart || dates[0]],
 ["windowEnd",   meta.asof || dates[dates.length - 1]],
 ["firstItem",   dates[0]],
 ["lastItem",    dates[dates.length - 1]],
 ["items",       String(items.length)],
 ["days",        String(dates.length)],
 ["built",       dateFmt("%Y-%m-%dT%H:%M:%S", new Date())],
 ["license",     "CC BY-SA 4.0, Wikipedia"]].forEach(function (kv) {
    sql.exec("insert into news_meta (Prop, Val) values (?, ?);", kv);
});

/* No noiselist and qMinWordLen 1: the corpus cannot afford either, but
   this index rebuilds in well under a second, and in news text the short
   tokens -- US, EU, GET, Go -- are exactly what gets searched for.
   The word expressions match the corpus so query behaviour is the same. */
var EXPRS = "'[\\ualnum]{2,99}', " +
            "'[\\ualnum$%@\\-_+#]{2,99}', " +
            "'\\digit{1,99}\\.=[0-9.]{1,99}', " +
            "'\\bound[CDR]=\\F\\space'";
sql.set({ noiseList: [] });
sql.set({ qMinWordLen: 1 });
var t0 = Date.now();
sql.exec("create fulltext index news_items_cx on news(Doc, Topic) " +
         "with wordexpressions (" + EXPRS + ");");
sql.exec("create index news_date on news(Date);");
sql.exec("create index news_sect on news(Section);");

/* The event ARTICLES arrive from kiwix-import, which builds no index --
   it is a staging importer. Indexing them here means one run of this
   script leaves the whole news database usable, which is what a daily
   rebuild needs; doing it by hand is how a rebuilt database ends up
   searchable for items and silently not for articles. */
var hasArticles = false, articlesIndexed = false;
sql.exec("select NAME from SYSTABLES where NAME = ?;", ["wikipedia_en_news"],
         { maxRows: 1 }, function () { hasArticles = true; });
if (hasArticles) {
    sql.exec("select NAME from SYSINDEX where TBNAME = ?;", ["wikipedia_en_news"],
             { maxRows: 9 }, function () { articlesIndexed = true; });
    if (!articlesIndexed) {
        var t1 = Date.now();
        sql.exec("create fulltext index news_cx on wikipedia_en_news(Doc) " +
                 "with wordexpressions (" + EXPRS + ");");
        sql.exec("create index news_src on wikipedia_en_news(SrcPath);");
        printf("articles : indexed in %.2f s\n", (Date.now() - t1) / 1000);
    }
}
printf("indexed  : %.2f s\n", (Date.now() - t0) / 1000);
printf("written  : %d rows in %s\n", items.length, DB);
