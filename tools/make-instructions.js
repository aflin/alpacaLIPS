/* Generate web/lib/corpus-inventory.js from what the corpus actually holds.
 *
 *   rampart tools/make-instructions.js [--db DIR] [--out FILE]
 *
 * The MCP server opens its instructions with a sentence describing the
 * corpus, and that sentence was a string literal: it said 48,033,082
 * documents from 171 archives long after the corpus held 49,947,943 in
 * 215, and it never mentioned Project Gutenberg or Wikibooks at all, so
 * two whole collections were invisible to every model that read it.
 *
 * The build writes it instead, once, from lips_sources. The runtime
 * requires the result and does no counting of its own -- a server should
 * not be querying its own catalogue to describe itself, and a published
 * runtime should already know what it ships with.
 *
 * Run by build.sh at the end of the merge stage, which is the point at
 * which lips_sources is final.
 */
rampart.globalize(rampart.utils);
var Sql = require("rampart-sql");

var DB = "", OUT = "";
for (var i = 2; i < process.argv.length; i++) {
    if (process.argv[i] === "--db") DB = process.argv[++i];
    else if (process.argv[i] === "--out") OUT = process.argv[++i];
}
var HERE = (process.scriptPath || ".").replace(/[\/]tools[\/]?$/, "");
if (!DB)  DB  = HERE + "/build/corpus";
if (!OUT) OUT = HERE + "/web/lib/corpus-inventory.js";

/* How each collection should read to someone deciding where to look.
   A name not listed here is passed through as it is stored, so a new
   collection appears in the text the day it is merged rather than
   silently missing. */
var NAMES = {
    wikipedia:     "Wikipedia",
    wiktionary:    "Wiktionary",
    wikisource:    "Wikisource",
    wikiquote:     "Wikiquote",
    wikiversity:   "Wikiversity",
    wikivoyage:    "Wikivoyage",
    wikibooks:     "Wikibooks",
    stackoverflow: "Stack Overflow",
    stackexchange: "Stack Exchange sites",
    ifixit:        "iFixit repair guides",
    gutenberg:     "Project Gutenberg",
    zimgit:        "offline reference PDFs"
};

function human(n) {
    if (n >= 1000000) return (n / 1000000).toFixed(1) + "M";
    if (n >= 100000)  return Math.round(n / 1000) + "K";
    return String(n).replace(/\B(?=(\d{3})+$)/g, ",");
}

var sql = new Sql.init(DB);
var byColl = {}, archives = {}, docs = 0, nArch = 0, lo = "", hi = "";
sql.exec("select Collection, Docs, Asof from lips_sources;", { maxRows: 5000 },
         function (r) {
    var c = String(r.Collection || "other"), n = Number(r.Docs) || 0;
    byColl[c] = (byColl[c] || 0) + n;
    archives[c] = (archives[c] || 0) + 1;
    docs += n; nArch++;
    var a = String(r.Asof || "");
    if (a.length >= 7) {
        if (!lo || a < lo) lo = a;
        if (!hi || a > hi) hi = a;
    }
});
if (!nArch) {
    printf("no rows in lips_sources at %s -- not writing %s\n", DB, OUT);
    process.exit(1);
}

/* Largest first: a model choosing where to look wants the big
   collections named before the small ones. */
var order = Object.keys(byColl).sort(function (a, b) {
    return byColl[b] - byColl[a];
});
var parts = order.map(function (c) {
    var name = NAMES[c] || c, unit = "";
    /* "161 Stack Exchange sites" rather than "Stack Exchange sites": how
       many sites is what tells a model how wide that collection is. The
       others read better with the unit after the number. */
    if (c === "stackexchange") name = archives[c] + " " + name;
    if (c === "gutenberg")     unit = " books";
    return name + " " + human(byColl[c]) + unit;
});

var text =
    "An offline corpus of " +
    String(docs).replace(/\B(?=(\d{3})+$)/g, ",") + " documents from " + nArch +
    " archives: " + parts.join(", ") + ". Keyword retrieval ranked across " +
    "the whole corpus. Snapshots taken " + lo.substring(0, 7) + " to " +
    hi.substring(0, 7) + ", so nothing later is in it.";

var out =
    "/* GENERATED by tools/make-instructions.js -- do not edit.\n" +
    " *\n" +
    " * What the corpus holds, written at build time so the server never\n" +
    " * counts its own catalogue to describe itself, and so a published\n" +
    " * runtime ships knowing what came with it. Regenerated by the merge\n" +
    " * stage of build.sh, which is where lips_sources becomes final.\n" +
    " *\n" +
    " * Written " + dateFmt("%Y-%m-%d %H:%M", new Date()) + " from " + DB + "\n" +
    " */\n" +
    "module.exports = {\n" +
    "    docs: " + docs + ",\n" +
    "    archives: " + nArch + ",\n" +
    "    collections: " + JSON.stringify(byColl) + ",\n" +
    "    asof: " + JSON.stringify(lo.substring(0, 7) + " to " + hi.substring(0, 7)) + ",\n" +
    "    text: " + JSON.stringify(text) + "\n" +
    "};\n";

fprintf(OUT, "%s", out);
printf("wrote %s\n", OUT);
printf("  %s documents, %d archives, %d collections, snapshots %s to %s\n",
       String(docs).replace(/\B(?=(\d{3})+$)/g, ","), nArch, order.length,
       lo.substring(0, 7), hi.substring(0, 7));
printf("\n%s\n", text);
